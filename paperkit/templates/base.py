"""Shared machinery for all journal template writers."""
from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

from ..model import DECLARATION_KEYS, Paper
from ..text import to_latex


@dataclass
class Variant:
    key: str                 # output file stem, e.g. "sigconf"
    options: str             # \documentclass options
    description: str
    twocolumn: bool = False
    extra: dict = field(default_factory=dict)


class Writer:
    """Base writer.  Subclasses set the class attributes and override the hooks they need."""

    key = "base"                     # output folder name
    title = "Base"
    docclass = "article"
    cite = "citep"                   # citation command used in the body
    bottomrule = r"\bottomrule"
    bib_name = "references"          # .bib file name (without extension)
    figure_pos = "htbp"
    table_pos = "htbp"
    variants: list[Variant] = []
    publisher_files: list[str] = []  # files/folders needed next to the .tex (provided by the publisher)
    notes = ""                       # shown in the output README

    # ------------------------------------------------------------------ helpers
    def t(self, s: str) -> str:
        return to_latex(s, self.cite)

    def keywords_sep(self) -> str:
        return ", "

    def label(self, kind: str, label: str) -> str:
        return r"\label{" + label + "}" if label else ""

    # ------------------------------------------------------------------ entry point
    # added to every preamble: robust tables, breakable URLs, no overfull lines from long words
    COMMON_PREAMBLE = [r"\usepackage{tabularx}", r"\setlength{\emergencystretch}{1.5em}", ""]

    def render(self, paper: Paper, v: Variant) -> str:
        L = []
        L += self.header(paper, v)
        L += [r"\PassOptionsToPackage{hyphens}{url}"]
        L += self.preamble(paper, v)
        L += self.COMMON_PREAMBLE
        L += [r"\begin{document}", ""]
        L += self.frontmatter(paper, v)
        L += self.body(paper.main_blocks(), v)
        L += self.after_body(paper, v)
        text = "\n".join(L).rstrip() + "\n"
        while "\n\n\n" in text:
            text = text.replace("\n\n\n", "\n\n")
        return text

    def header(self, paper: Paper, v: Variant) -> list[str]:
        return [
            "%% " + "=" * 74,
            f"%% {self.title} -- variant: {v.key}",
            f"%% {v.description}",
            "%% Generated by paperkit (https://github.com/Apurba94/paperkit). Edit the paper",
            "%% source (paper.md / references.bib) and rebuild rather than editing this file.",
            "%% " + "=" * 74,
            "",
        ]

    def preamble(self, paper: Paper, v: Variant) -> list[str]:
        return [rf"\documentclass[{v.options}]{{{self.docclass}}}", ""]

    def frontmatter(self, paper: Paper, v: Variant) -> list[str]:
        raise NotImplementedError

    def after_body(self, paper: Paper, v: Variant) -> list[str]:
        """Back matter, appendix and references (order differs between publishers)."""
        L = self.backmatter(paper, v)
        L += self.appendix(paper, v)
        L += self.references(paper, v)
        L += [r"\end{document}"]
        return L

    # ------------------------------------------------------------------ body
    def body(self, blocks: list[tuple], v: Variant, appendix: bool = False) -> list[str]:
        L: list[str] = []
        for b in blocks:
            kind = b[0]
            if kind == "section":
                L += ["", self.section_cmd("section", b, v), ""]
            elif kind == "subsection":
                L += [self.section_cmd("subsection", b, v), ""]
            elif kind == "subsubsection":
                L += [self.section_cmd("subsubsection", b, v), ""]
            elif kind == "appendix":
                L += ["", self.appendix_section(b, v), ""]
            elif kind == "p":
                L += [self.t(b[1]), ""]
            elif kind in ("list", "enum"):
                env = "itemize" if kind == "list" else "enumerate"
                L += [rf"\begin{{{env}}}"] + [r"\item " + self.t(x) for x in b[1]] + [rf"\end{{{env}}}", ""]
            elif kind == "eq":
                L += [r"\begin{equation}", b[1] + self.label("eq", b[2]), r"\end{equation}", ""]
            elif kind == "figure":
                L += self.figure(b, v) + [""]
            elif kind == "table":
                L += self.table(b, v) + [""]
        return L

    def section_cmd(self, cmd: str, b: tuple, v: Variant) -> str:
        return rf"\{cmd}{{{self.t(b[1])}}}" + self.label(cmd, b[2] if len(b) > 2 else "")

    def appendix_section(self, b: tuple, v: Variant) -> str:
        return rf"\section{{{self.t(b[1])}}}" + self.label("section", b[2] if len(b) > 2 else "")

    # ------------------------------------------------------------------ floats
    def figure_name(self, path: str) -> str:
        return Path(path).name

    def figure(self, b: tuple, v: Variant) -> list[str]:
        _, label, path, caption, wide, width = b
        span = wide and v.twocolumn
        env = "figure*" if span else "figure"
        w = r"\textwidth" if span else (r"\linewidth" if width >= 0.999 else f"{width:.2f}\\linewidth")
        L = [rf"\begin{{{env}}}[{self.figure_pos}]", r"\centering",
             rf"\includegraphics[width={w}]{{{self.figure_name(path)}}}"]
        L += self.figure_extra(b, v)
        L += [rf"\caption{{{self.t(caption)}}}" + self.label("figure", label), rf"\end{{{env}}}"]
        return L

    def figure_extra(self, b: tuple, v: Variant) -> list[str]:
        return []

    def support_files(self, folder: Path) -> None:
        """Write any helper files the template needs next to the .tex (override if needed)."""

    def bib_for_template(self, bib: str) -> str:
        """Adjust the shared .bib for quirks of this publisher's bibliography style (override if needed)."""
        return bib

    def tabular(self, spec: str, header: list, rows: list, wide: bool) -> tuple[str, str]:
        """Opening/closing lines of the tabular. Tables with a wrapping (X) column use tabularx, which
        always fits the line width; other wide tables are spread over the full width."""
        if "X" in spec:
            cs = "".join(r">{\raggedright\arraybackslash}X" if c == "X" else c for c in spec)
            return r"\begin{tabularx}{\linewidth}{@{}" + cs + "@{}}", r"\end{tabularx}"
        if wide:
            return r"\begin{tabular*}{\linewidth}{@{\extracolsep{\fill}}" + spec + "@{}}", r"\end{tabular*}"
        return r"\begin{tabular}{@{}" + spec + "@{}}", r"\end{tabular}"

    def table(self, b: tuple, v: Variant) -> list[str]:
        _, label, caption, header, rows, spec, wide = b
        span = wide and v.twocolumn
        env = "table*" if span else "table"
        begin, end = self.tabular(spec, header, rows, wide)
        L = [rf"\begin{{{env}}}[{self.table_pos}]", r"\centering",
             rf"\caption{{{self.t(caption)}}}" + self.label("table", label), r"\footnotesize", begin, r"\toprule",
             " & ".join(self.t(str(h)) for h in header) + r" \\", r"\midrule"]
        L += [" & ".join(self.t(str(c)) for c in row) + r" \\" for row in rows]
        L += [self.bottomrule, end, rf"\end{{{env}}}"]
        return L

    # ------------------------------------------------------------------ back matter
    def ai_statement(self, paper: Paper) -> str:
        return paper.ai_use

    def acknowledgement_text(self, paper: Paper) -> str:
        parts = [paper.acknowledgements, self.ai_statement(paper)]
        return " ".join(self.t(p) for p in parts if p)

    def declarations_list(self, paper: Paper, keys=None) -> list[tuple[str, str]]:
        keys = keys or [k for k, _ in DECLARATION_KEYS]
        names = dict(DECLARATION_KEYS)
        return [(names[k], paper.declaration(k)) for k in keys]

    def backmatter(self, paper: Paper, v: Variant) -> list[str]:
        L = []
        ack = self.acknowledgement_text(paper)
        if ack:
            L += [r"\section*{Acknowledgments}", ack, ""]
        for name, text in self.declarations_list(paper):
            L += [rf"\section*{{{name}}}", self.t(text), ""]
        return L

    def appendix(self, paper: Paper, v: Variant) -> list[str]:
        blocks = paper.appendix_blocks()
        if not blocks:
            return []
        return ["", r"\appendix", ""] + self.body(blocks, v, appendix=True)

    def references(self, paper: Paper, v: Variant) -> list[str]:
        return [rf"\bibliography{{{self.bib_name}}}", ""]

    # ------------------------------------------------------------------ authors
    def author_list(self, paper: Paper) -> str:
        names = [a.name for a in paper.authors]
        return names[0] if len(names) == 1 else ", ".join(names[:-1]) + " and " + names[-1]
